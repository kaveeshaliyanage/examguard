"""Publish the synthetic training set, model artifacts and training notebook to Kaggle.

Authentication comes from the official Kaggle CLI: ``KAGGLE_API_TOKEN`` or
``~/.kaggle/access_token`` (or ``~/.kaggle/kaggle.json``). This module never reads or prints
the credential itself; it shells out to ``kaggle``.

    python -m app.training.kaggle_publish dataset --data data
    python -m app.training.kaggle_publish notebook --dataset <owner>/examguard-synthetic-fusion-rows
    python -m app.training.kaggle_publish models --models models
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
AI_ROOT = REPO_ROOT / "ai"
NOTEBOOK_TEMPLATE = REPO_ROOT / "kaggle" / "notebooks" / "train_fusion.ipynb"

DATASET_SLUG = "examguard-synthetic-fusion-rows"
MODELS_SLUG = "examguard-fusion-models"
NOTEBOOK_SLUG = "examguard-train-fusion"


def _without_cache(info: tarfile.TarInfo) -> tarfile.TarInfo | None:
    if "__pycache__" in info.name or info.name.endswith(".pyc"):
        return None
    return info


def _kaggle(*args: str, cwd: Path | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "kaggle", *args],
        cwd=cwd,
        text=True,
        capture_output=True,
    )


def _run(*args: str, cwd: Path | None = None) -> None:
    result = _kaggle(*args, cwd=cwd)
    if result.returncode != 0:
        sys.stderr.write(result.stdout)
        sys.stderr.write(result.stderr)
        raise SystemExit(f"kaggle {' '.join(args)} failed with {result.returncode}")
    sys.stdout.write(result.stdout)


def username() -> str:
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()
    value = api.config_values.get("username")
    if not value:
        raise SystemExit("Kaggle credentials are missing; save a token to ~/.kaggle/access_token")
    return str(value)


def _dataset_metadata(owner: str, slug: str, title: str, subtitle: str, description: str) -> dict:
    return {
        "title": title,
        "id": f"{owner}/{slug}",
        "subtitle": subtitle,
        "description": description,
        "licenses": [{"name": "CC0-1.0"}],
        "isPrivate": True,
        "keywords": ["education"],
    }


def stage_dataset(data_dir: Path, out_dir: Path) -> Path:
    """Copy rows plus the code snapshot the notebook needs into one upload folder."""
    out_dir.mkdir(parents=True, exist_ok=True)
    for name in ("pairs.jsonl", "incidents.jsonl", "manifest.json"):
        source = data_dir / name
        if not source.exists():
            raise SystemExit(f"{source} is missing; run app.training.export first")
        shutil.copy2(source, out_dir / name)

    # Kaggle's uploader skips nested directories, so ship the package as one archive.
    archive = out_dir / "code.tar.gz"
    if archive.exists():
        archive.unlink()
    with tarfile.open(archive, "w:gz") as bundle:
        bundle.add(AI_ROOT / "app", arcname="app", filter=_without_cache)

    owner = username()
    metadata = _dataset_metadata(
        owner,
        DATASET_SLUG,
        "ExamGuard synthetic fusion training rows",
        "Pair and incident feature rows generated by the ExamGuard simulator",
        (
            "Feature rows exported from the ExamGuard synthetic cohort generator, plus the "
            "analysis code needed to train the fusion models offline. Labels describe the "
            "simulator, not real misconduct. Do not treat metrics as real-world validity."
        ),
    )
    (out_dir / "dataset-metadata.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
    )
    return out_dir


def _create_or_version(staged: Path, message: str) -> None:
    """Create the dataset, or upload a new version when the slug is taken.

    The CLI exits 0 while printing "already in use", so the output decides.
    """
    created = _kaggle("datasets", "create", "-p", str(staged), "-r", "skip")
    output = (created.stdout + created.stderr).lower()
    if created.returncode == 0 and "error" not in output:
        sys.stdout.write(created.stdout)
        return
    _run("datasets", "version", "-p", str(staged), "-m", message, "-r", "skip")


def publish_dataset(data_dir: Path, build_dir: Path, message: str) -> str:
    staged = stage_dataset(data_dir, build_dir)
    _create_or_version(staged, message)
    return f"{username()}/{DATASET_SLUG}"


def publish_models(models_dir: Path, build_dir: Path, message: str) -> str:
    """Upload the trained joblib artifacts as a private model dataset."""
    artifacts = sorted(models_dir.glob("*.joblib"))
    if not artifacts:
        raise SystemExit(f"no .joblib artifacts in {models_dir}; run app.training.train first")
    build_dir.mkdir(parents=True, exist_ok=True)
    for path in models_dir.glob("*"):
        if path.is_file():
            shutil.copy2(path, build_dir / path.name)

    owner = username()
    metadata = _dataset_metadata(
        owner,
        MODELS_SLUG,
        "ExamGuard fusion models",
        "Calibrated pair and incident fusion artifacts with metadata and model card",
        (
            "Trained on synthetic cohorts only. The score is a review priority, not a "
            "probability of misconduct. Keep MODEL_CARD.md with every artifact."
        ),
    )
    (build_dir / "dataset-metadata.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
    )
    _create_or_version(build_dir, message)
    return f"{owner}/{MODELS_SLUG}"


def publish_notebook(dataset_ref: str, build_dir: Path) -> str:
    owner = username()
    build_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(NOTEBOOK_TEMPLATE, build_dir / "train_fusion.ipynb")
    metadata = {
        "id": f"{owner}/{NOTEBOOK_SLUG}",
        "title": "ExamGuard train fusion",
        "code_file": "train_fusion.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": False,
        "enable_tpu": False,
        "enable_internet": False,
        "dataset_sources": [dataset_ref],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (build_dir / "kernel-metadata.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
    )
    _run("kernels", "push", "-p", str(build_dir))
    return f"{owner}/{NOTEBOOK_SLUG}"


def main() -> None:
    parser = argparse.ArgumentParser(description="Kaggle publishing helpers")
    parser.add_argument("command", choices=["dataset", "models", "notebook", "whoami"])
    parser.add_argument("--data", type=Path, default=AI_ROOT / "data")
    parser.add_argument("--models", type=Path, default=AI_ROOT / "models")
    parser.add_argument("--build", type=Path, default=AI_ROOT / "build" / "kaggle")
    parser.add_argument("--dataset", default=None, help="dataset ref for the notebook")
    parser.add_argument("--message", default="refresh synthetic training rows")
    args = parser.parse_args()

    if args.command == "whoami":
        print(username())
    elif args.command == "dataset":
        print(publish_dataset(args.data, args.build / "dataset", args.message))
    elif args.command == "models":
        print(publish_models(args.models, args.build / "models", args.message))
    else:
        if not args.dataset:
            raise SystemExit("--dataset <owner>/<slug> is required")
        print(publish_notebook(args.dataset, args.build / "notebook"))


if __name__ == "__main__":
    main()
