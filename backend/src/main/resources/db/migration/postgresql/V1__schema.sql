-- ExamGuard AI initial schema (PostgreSQL 16)
-- Mirrors mysql/V1__schema.sql. Booleans are native BOOLEAN; timestamps are
-- timezone-aware because Hibernate maps Instant to TIMESTAMP_UTC.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(255) NOT NULL,
    role          VARCHAR(32)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX uk_user_email ON app_user (email);

CREATE TABLE exam (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code             VARCHAR(64)  NOT NULL,
    title            VARCHAR(255) NOT NULL,
    description      TEXT         NULL,
    duration_minutes INT          NOT NULL,
    status           VARCHAR(32)  NOT NULL,
    created_by       BIGINT       NOT NULL,
    opens_at         TIMESTAMP(6) WITH TIME ZONE NULL,
    closes_at        TIMESTAMP(6) WITH TIME ZONE NULL,
    allow_extension  BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_exam_creator FOREIGN KEY (created_by) REFERENCES app_user (id)
);
CREATE UNIQUE INDEX uk_exam_code ON exam (code);

CREATE TABLE exam_permission (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    exam_id BIGINT      NOT NULL,
    user_id BIGINT      NOT NULL,
    level   VARCHAR(32) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_permission_exam_user UNIQUE (exam_id, user_id),
    CONSTRAINT fk_permission_exam FOREIGN KEY (exam_id) REFERENCES exam (id),
    CONSTRAINT fk_permission_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);

CREATE TABLE question (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    exam_id     BIGINT NOT NULL,
    order_index INT    NOT NULL,
    prompt      TEXT   NOT NULL,
    max_words   INT    NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_question_exam_order UNIQUE (exam_id, order_index),
    CONSTRAINT fk_question_exam FOREIGN KEY (exam_id) REFERENCES exam (id)
);

CREATE TABLE resource_rule (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    exam_id        BIGINT       NOT NULL,
    category       VARCHAR(32)  NOT NULL,
    domain_pattern VARCHAR(255) NOT NULL,
    note           TEXT         NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_rule_exam FOREIGN KEY (exam_id) REFERENCES exam (id)
);

CREATE TABLE candidate (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    exam_id       BIGINT       NOT NULL,
    code          VARCHAR(64)  NOT NULL,
    display_label VARCHAR(255) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_candidate_exam_code UNIQUE (exam_id, code),
    CONSTRAINT fk_candidate_exam FOREIGN KEY (exam_id) REFERENCES exam (id)
);

CREATE TABLE attempt (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    exam_id               BIGINT      NOT NULL,
    candidate_id          BIGINT      NOT NULL,
    status                VARCHAR(32) NOT NULL,
    started_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    submitted_at          TIMESTAMP(6) WITH TIME ZONE NULL,
    last_seen_at          TIMESTAMP(6) WITH TIME ZONE NULL,
    extension_connected   BOOLEAN     NOT NULL DEFAULT FALSE,
    late_submission       BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_attempt_exam_candidate UNIQUE (exam_id, candidate_id),
    CONSTRAINT fk_attempt_exam FOREIGN KEY (exam_id) REFERENCES exam (id),
    CONSTRAINT fk_attempt_candidate FOREIGN KEY (candidate_id) REFERENCES candidate (id)
);

CREATE TABLE answer_revision (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    attempt_id       BIGINT NOT NULL,
    question_id      BIGINT NOT NULL,
    revision_no      INT    NOT NULL,
    text             TEXT   NULL,
    selected_options TEXT   NULL,
    client_seq       BIGINT NOT NULL,
    saved_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_revision_attempt_question_no UNIQUE (attempt_id, question_id, revision_no),
    CONSTRAINT fk_revision_attempt FOREIGN KEY (attempt_id) REFERENCES attempt (id),
    CONSTRAINT fk_revision_question FOREIGN KEY (question_id) REFERENCES question (id)
);
CREATE INDEX idx_revision_attempt_question ON answer_revision (attempt_id, question_id);

CREATE TABLE activity_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    attempt_id      BIGINT       NOT NULL,
    client_event_id VARCHAR(100) NOT NULL,
    event_type      VARCHAR(32)  NOT NULL,
    domain          VARCHAR(255) NULL,
    occurred_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    received_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tab_id          INT          NULL,
    metadata_json   TEXT         NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_event_attempt_client UNIQUE (attempt_id, client_event_id),
    CONSTRAINT fk_event_attempt FOREIGN KEY (attempt_id) REFERENCES attempt (id)
);
CREATE INDEX idx_event_attempt_time ON activity_event (attempt_id, occurred_at);

CREATE TABLE analysis_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    exam_id       BIGINT      NOT NULL,
    status        VARCHAR(32) NOT NULL,
    model_version VARCHAR(64) NULL,
    input_hash    VARCHAR(128) NULL,
    error         TEXT        NULL,
    created_by    BIGINT      NULL,
    started_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at   TIMESTAMP(6) WITH TIME ZONE NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_run_exam FOREIGN KEY (exam_id) REFERENCES exam (id),
    CONSTRAINT fk_run_creator FOREIGN KEY (created_by) REFERENCES app_user (id)
);
CREATE INDEX idx_run_exam_time ON analysis_run (exam_id, started_at);

CREATE TABLE finding (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    exam_id          BIGINT      NOT NULL,
    analysis_run_id  BIGINT      NOT NULL,
    type             VARCHAR(32) NOT NULL,
    candidate_a_id   BIGINT      NOT NULL,
    candidate_b_id   BIGINT      NULL,
    question_id      BIGINT      NULL,
    priority_score   DOUBLE PRECISION NOT NULL,
    priority_band    VARCHAR(32) NOT NULL,
    coverage_warning BOOLEAN     NOT NULL DEFAULT FALSE,
    status           VARCHAR(32) NOT NULL,
    summary          TEXT        NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_finding_exam FOREIGN KEY (exam_id) REFERENCES exam (id),
    CONSTRAINT fk_finding_run FOREIGN KEY (analysis_run_id) REFERENCES analysis_run (id),
    CONSTRAINT fk_finding_candidate_a FOREIGN KEY (candidate_a_id) REFERENCES candidate (id),
    CONSTRAINT fk_finding_candidate_b FOREIGN KEY (candidate_b_id) REFERENCES candidate (id)
);
CREATE INDEX idx_finding_exam_type_score ON finding (exam_id, type, priority_score);

CREATE TABLE evidence_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    finding_id    BIGINT      NOT NULL,
    source        VARCHAR(32) NOT NULL,
    weight        DOUBLE PRECISION NOT NULL,
    question_id   BIGINT      NULL,
    detail        TEXT        NULL,
    metadata_json TEXT        NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_evidence_finding FOREIGN KEY (finding_id) REFERENCES finding (id) ON DELETE CASCADE
);
CREATE INDEX idx_evidence_finding ON evidence_item (finding_id);

CREATE TABLE review_decision (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    finding_id  BIGINT      NOT NULL,
    reviewer_id BIGINT      NOT NULL,
    outcome     VARCHAR(32) NOT NULL,
    rationale   TEXT        NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_decision_finding FOREIGN KEY (finding_id) REFERENCES finding (id),
    CONSTRAINT fk_decision_reviewer FOREIGN KEY (reviewer_id) REFERENCES app_user (id)
);
CREATE INDEX idx_decision_finding ON review_decision (finding_id);

CREATE TABLE audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    actor_user_id BIGINT       NULL,
    exam_id       BIGINT       NULL,
    action        VARCHAR(100) NOT NULL,
    entity_type   VARCHAR(100) NOT NULL,
    entity_id     BIGINT       NULL,
    detail_json   TEXT         NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_audit_actor FOREIGN KEY (actor_user_id) REFERENCES app_user (id)
);
CREATE INDEX idx_audit_exam_time ON audit_log (exam_id, created_at);
