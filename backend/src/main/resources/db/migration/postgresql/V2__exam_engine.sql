-- Phase 1: typed questions, attempt scoring, strike tracking, manual grading.

ALTER TABLE exam
    ADD COLUMN max_strikes INT NOT NULL DEFAULT 3,
    ADD COLUMN instructions TEXT NULL;

ALTER TABLE question
    ADD COLUMN type            VARCHAR(32)   NOT NULL DEFAULT 'ESSAY',
    ADD COLUMN points          DECIMAL(6, 2) NOT NULL DEFAULT 1.00,
    ADD COLUMN grading_mode    VARCHAR(16)   NOT NULL DEFAULT 'MANUAL',
    ADD COLUMN content_json    TEXT          NULL,
    ADD COLUMN answer_key_json TEXT          NULL,
    ADD COLUMN explanation     TEXT          NULL;

UPDATE question SET content_json = '{}' WHERE content_json IS NULL;

ALTER TABLE question
    ALTER COLUMN content_json SET NOT NULL;

ALTER TABLE attempt
    ADD COLUMN student_user_id    BIGINT        NULL,
    ADD COLUMN strike_count       INT           NOT NULL DEFAULT 0,
    ADD COLUMN max_strikes        INT           NOT NULL DEFAULT 3,
    ADD COLUMN terminated_at      TIMESTAMP(6) WITH TIME ZONE NULL,
    ADD COLUMN termination_reason VARCHAR(32)   NULL,
    ADD COLUMN score_points       DECIMAL(8, 2) NULL,
    ADD COLUMN max_points         DECIMAL(8, 2) NULL,
    ADD COLUMN graded_at          TIMESTAMP(6) WITH TIME ZONE NULL,
    ADD COLUMN released_at        TIMESTAMP(6) WITH TIME ZONE NULL,
    ADD CONSTRAINT fk_attempt_student FOREIGN KEY (student_user_id) REFERENCES app_user (id);

CREATE INDEX idx_attempt_student ON attempt (student_user_id);

CREATE TABLE answer_grade (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    attempt_id      BIGINT        NOT NULL,
    question_id     BIGINT        NOT NULL,
    awarded_points  DECIMAL(8, 2) NOT NULL,
    max_points      DECIMAL(8, 2) NOT NULL,
    mode            VARCHAR(16)   NOT NULL,
    graded_by       BIGINT        NULL,
    comment         TEXT          NULL,
    graded_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_grade_attempt_question UNIQUE (attempt_id, question_id),
    CONSTRAINT fk_grade_attempt FOREIGN KEY (attempt_id) REFERENCES attempt (id),
    CONSTRAINT fk_grade_question FOREIGN KEY (question_id) REFERENCES question (id),
    CONSTRAINT fk_grade_reviewer FOREIGN KEY (graded_by) REFERENCES app_user (id)
);

CREATE TABLE integrity_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    attempt_id    BIGINT       NOT NULL,
    episode_key   VARCHAR(100) NOT NULL,
    signal_type   VARCHAR(32)  NOT NULL,
    strike_index  INT          NULL,
    occurred_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    received_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    client_seq    BIGINT       NULL,
    metadata_json TEXT         NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_integrity_attempt_episode UNIQUE (attempt_id, episode_key),
    CONSTRAINT fk_integrity_attempt FOREIGN KEY (attempt_id) REFERENCES attempt (id)
);

CREATE INDEX idx_integrity_attempt_time ON integrity_event (attempt_id, occurred_at);
